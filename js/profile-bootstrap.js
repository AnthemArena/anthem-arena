// Creates (or restores) the signed-in visitor's profile. Shared by the vote page and the feed so a brand-new visitor never
// ends up as "Anonymous" with no avatar.
//
// Why this exists: the security rules only let a visitor write profiles/{their Firebase uid}. A first-time visitor used to
// get a made-up id (IP + fingerprint) and the profile write for that id was refused, so they stayed Anonymous.
import { getChampionImageUrl } from './arcane-config.js';

const CHAMPIONS = ['Jinx', 'Vi', 'Caitlyn', 'Ekko', 'Jayce', 'Viktor', 'Heimerdinger'];
const ADJECTIVES = ['Epic', 'Legendary', 'Supreme', 'Elite', 'Mystic', 'Shadow', 'Golden', 'Silver', 'Royal', 'Grand', 'Swift', 'Fierce', 'Noble', 'Brave', 'Mighty'];
const NOUNS = ['Summoner', 'Champion', 'Voter', 'Fan', 'Hunter', 'Legend', 'Warrior', 'Scout', 'Ranger', 'Guardian', 'Hero', 'Seeker', 'Watcher', 'Striker', 'Sentinel'];

export function generateUsername(rand = Math.random) {
    return `${ADJECTIVES[Math.floor(rand() * ADJECTIVES.length)]}${NOUNS[Math.floor(rand() * NOUNS.length)]}${Math.floor(rand() * 1000)}`;
}

export function isPlaceholderName(name) {
    return !name || name === 'null' || name === 'undefined' || name === 'Anonymous';
}

// Resolves with the signed-in uid, waiting for the anonymous sign-in to finish; null if it never does.
export async function waitForAuthUid(auth, timeoutMs = 8000) {
    if (auth?.currentUser?.uid) return auth.currentUser.uid;
    const { onAuthStateChanged } = await import('https://www.gstatic.com/firebasejs/10.7.1/firebase-auth.js');
    return new Promise(resolve => {
        const timer = setTimeout(() => { off(); resolve(auth?.currentUser?.uid || null); }, timeoutMs);
        const off = onAuthStateChanged(auth, user => { if (user) { clearTimeout(timer); off(); resolve(user.uid); } });
    });
}

function saveLocal(profile) {
    const isPublic = profile.privacy?.isPublic ?? true;
    localStorage.setItem('username', profile.username);
    localStorage.setItem('tournamentUsername', profile.username);
    localStorage.setItem('avatar', JSON.stringify(profile.avatar || null));
    localStorage.setItem('isPublic', isPublic ? 'true' : 'false');
}

// Returns { username, created } or null if it could not be done.
export async function ensureOwnProfile() {
    try {
        const { db, auth } = await import('./firebase-config.js');
        const { doc, getDoc, setDoc } = await import('https://www.gstatic.com/firebasejs/10.7.1/firebase-firestore.js');
        const uid = await waitForAuthUid(auth);
        if (!uid) return null;
        localStorage.setItem('userId', uid);
        localStorage.setItem('tournamentUserId', uid);

        const ref = doc(db, 'profiles', uid);
        const snap = await getDoc(ref);
        if (snap.exists() && !isPlaceholderName(snap.data().username)) {
            saveLocal(snap.data());
            return { username: snap.data().username, created: false };
        }

        const username = generateUsername();
        const champion = CHAMPIONS[Math.floor(Math.random() * CHAMPIONS.length)];
        const avatar = { type: 'url', value: getChampionImageUrl(champion), name: champion };
        const privacy = { isPublic: true, messagePrivacy: 'everyone', emotePrivacy: 'everyone', showOnlineStatus: true };
        await setDoc(ref, { userId: uid, username, avatar, bio: '', privacy, unlockedAchievements: [], createdAt: Date.now(), autoGenerated: true }, { merge: true });
        saveLocal({ username, avatar, privacy });
        console.log('🎉 Profile created:', username);
        return { username, created: true };
    } catch (error) {
        console.error('❌ Could not create profile:', error);
        return null;
    }
}
