import { closingSoon, announcementToShow, formatLeft } from '../js/feed-strip-model.js';
let pass = 0, fail = 0;
const t = (n, ok) => { console.log(`  ${ok ? 'ok ' : 'FAIL'} ${n}`); ok ? pass++ : fail++; };
const now = Date.parse('2026-10-20T12:00:00Z');
const m = (id, h, status = 'live') => ({ matchId: `jinx-cup-1-group-1-match-${id}`, status, endDate: new Date(now + h * 3600e3).toISOString() });
const ms = [m(1, 50), m(2, 5), m(3, 20), m(4, 1, 'upcoming'), m(5, -2), { matchId: 'old-cup-group-1-match-1', status: 'live', endDate: new Date(now + 1e6).toISOString() }];
let r = closingSoon({ matches: ms, votes: [], now, cupId: 'jinx-cup-1' });
t('counts live, unexpired, current cup only', r.count === 3);
t('soonest deadline is next', r.next.matchId.endsWith('match-2') && r.msLeft === 5 * 3600e3);
r = closingSoon({ matches: ms, votes: [{ matchId: ms[1].matchId }], now, cupId: 'jinx-cup-1' });
t('voted matches drop out', r.count === 2 && r.next.matchId.endsWith('match-3'));
r = closingSoon({ matches: ms, votes: null, now, cupId: 'jinx-cup-1' });
t('logged out: everything open counts', r.count === 3);
r = closingSoon({ matches: [], votes: [], now });
t('nothing open', r.count === 0 && r.next === null);
r = closingSoon({ matches: [{ matchId: 'a', status: 'live' }], votes: [], now });
t('no deadline: counted, no countdown', r.count === 1 && r.next === null && r.nextId === 'a');
t('format days', formatLeft(50 * 3600e3) === '2d 2h');
t('format hours', formatLeft(5 * 3600e3 + 120e3) === '5h 2m');
t('format minutes', formatLeft(30e3) === '1m' && formatLeft(0) === 'closing now');
const cfg = { enabled: true, id: 'x', text: 'Hi', linkText: 'Go', linkUrl: '/matches', expires: '2026-10-23T20:00:00Z' };
t('announcement shows', announcementToShow(cfg, now).linkUrl === '/matches');
t('disabled hides', announcementToShow({ ...cfg, enabled: false }, now) === null);
t('expired hides', announcementToShow(cfg, Date.parse('2026-10-24T00:00:00Z')) === null);
t('dismissed id hides, new id shows', announcementToShow(cfg, now, 'x') === null && announcementToShow({ ...cfg, id: 'y' }, now, 'x') !== null);
t('javascript: and // links dropped', announcementToShow({ ...cfg, linkUrl: 'javascript:alert(1)' }, now).linkUrl === null && announcementToShow({ ...cfg, linkUrl: '//evil.com' }, now).linkUrl === null);
t('missing text hides', announcementToShow({ ...cfg, text: '' }, now) === null);
console.log(`${pass} passed${fail ? `, ${fail} FAILED` : ''}`); process.exit(fail ? 1 : 0);
